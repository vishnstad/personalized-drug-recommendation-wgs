"""
Phenotype and drug-group summary for the two project genes (CYP2C19, CYP2D6), built
from the live CPIC API (and the Neo4j graph if reachable). Writes docs/phenotypes_and_drugs.md.

Usage: python3 analysis/phenotype_drug_summary.py
"""
import json
import urllib.parse
import urllib.request
from collections import Counter, defaultdict
from pathlib import Path

API = "https://api.cpicpgx.org/v1/"
GENES = ["CYP2C19", "CYP2D6"]
OUT = Path(__file__).resolve().parent.parent / "docs" / "phenotypes_and_drugs.md"

# WHO ATC level-4 chemical/therapeutic subgroup names for the codes that occur here
# (entered manually from the WHO ATC index; CPIC supplies only the codes).
ATC4 = {
    "N06A": "Antidepressants", "N05A": "Antipsychotics", "N05B": "Anxiolytics",
    "N06B": "Psychostimulants / ADHD agents", "N06C": "Psycholeptic+psychoanaleptic combinations",
    "N06D": "Anti-dementia drugs", "N02A": "Opioids", "R05D": "Cough suppressants",
    "N07A": "Parasympathomimetics", "N07B": "Drugs for addictive disorders",
    "N07X": "Other nervous-system drugs", "A02B": "Peptic ulcer / GERD drugs (incl. PPIs)",
    "A03F": "Propulsives", "A04A": "Antiemetics", "B01A": "Antithrombotic agents",
    "C07A": "Beta-blockers", "C01B": "Antiarrhythmics (class I/III)",
    "J02A": "Systemic antimycotics", "D01A": "Topical antifungals", "D01B": "Systemic antifungals (dermatological)",
    "L02B": "Hormone antagonists (e.g. tamoxifen)", "L01X": "Other antineoplastics",
    "G04B": "Urologicals", "G04C": "BPH drugs", "R06A": "Systemic antihistamines",
    "M03B": "Centrally acting muscle relaxants", "S01E": "Antiglaucoma", "P01B": "Antimalarials",
}
ATC1 = {"A": "Alimentary/metabolism", "B": "Blood", "C": "Cardiovascular", "D": "Dermatological",
        "G": "Genito-urinary", "J": "Anti-infectives", "L": "Antineoplastic/immune", "M": "Musculoskeletal",
        "N": "Nervous system", "P": "Antiparasitic", "R": "Respiratory", "S": "Sensory organs"}


def get(path, count=False):
    req = urllib.request.Request(API + path, headers={"Prefer": "count=exact"} if count else {})
    with urllib.request.urlopen(req, timeout=60) as r:
        return int(r.headers["Content-Range"].split("/")[1]) if count else json.load(r)


def graph_phenotype_counts():
    try:
        import sys
        sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
        from retrieval.queries import get_driver
        d = get_driver()
        with d.session() as s:
            out = {g: s.run("MATCH (p:Phenotype {gene:$g}) RETURN count(p) AS n", g=g).single()["n"] for g in GENES}
            tot = s.run("MATCH (p:Phenotype) RETURN count(p) AS n").single()["n"]
        d.close()
        return out, tot
    except Exception:
        return None, None


def main():
    drugs = {d["drugid"]: d for d in get("drug?limit=1000")}
    guid = {g["id"]: g["name"] for g in get("guideline")}
    md = ["# Phenotypes and drug groupings — CYP2C19 and CYP2D6", "",
          "Generated by `analysis/phenotype_drug_summary.py` from the live CPIC API "
          "(and Neo4j where noted). Re-run to refresh.", ""]

    gcounts, gtotal = graph_phenotype_counts()
    md += ["## 1. Phenotypes", ""]
    for gene in GENES:
        rows = get(f"gene_result?genesymbol=eq.{gene}")
        md += [f"### {gene}", "",
               "| Phenotype (CPIC `gene_result`) | EHR priority | Raw CPIC diplotype rows mapping to it | "
               "Freq. European | Freq. East Asian | Freq. Sub-Saharan African | Freq. Central/South Asian |",
               "|---|---|---|---|---|---|---|"]
        # CYP2D6 stores one gene_result row per activity-score value, so group by phenotype
        # label and sum the per-population frequencies (they are fractions of the population).
        grouped = defaultdict(lambda: {"scores": [], "ehr": None, "freq": defaultdict(float)})
        for r in rows:
            g = grouped[r["result"].strip()]
            g["ehr"] = g["ehr"] or r.get("ehrpriority")
            if r.get("activityscore") not in (None, "n/a"):
                g["scores"].append(r["activityscore"])
            for k, v in (r.get("frequency") or {}).items():
                g["freq"][k] += v or 0
        total_dips = 0
        md[-2:] = ["| Phenotype | Activity score(s) | EHR priority | Raw CPIC diplotype rows | "
                   "European | East Asian | Sub-Saharan African | Central/South Asian |",
                   "|---|---|---|---|---|---|---|---|"]
        for label, g in sorted(grouped.items()):
            n = get(f"diplotype?genesymbol=eq.{gene}&generesult=eq.{urllib.parse.quote(label)}&limit=1", count=True)
            total_dips += n
            fmt = lambda k: f"{100 * g['freq'][k]:.1f}%"
            md.append(f"| {label} | {', '.join(sorted(set(g['scores']))) or 'n/a'} | {g['ehr'] or '–'} | {n:,} | "
                      f"{fmt('European')} | {fmt('East Asian')} | {fmt('Sub-Saharan African')} | {fmt('Central/South Asian')} |")
        rows = list(grouped)
        md += ["", f"{len(rows)} CPIC phenotype categories; {total_dips:,} raw diplotype rows resolve to them."
               + (f" Neo4j holds **{gcounts[gene]}** `Phenotype` nodes for {gene} (the CPIC categories above plus a "
                  f"'No Result' placeholder phenotype that CPIC recommendations reference)." if gcounts else ""), ""]
    if gtotal is not None:
        md += [f"Whole graph: **{gtotal}** `Phenotype` nodes across all genes.", ""]

    md += ["## 2. Drugs linked to each gene (non-removed CPIC pairs)", ""]
    pair_sets = {}
    for gene in GENES:
        pairs = get(f"pair?genesymbol=eq.{gene}&removed=eq.false&limit=500")
        pair_sets[gene] = pairs
        lv = Counter(p["cpiclevel"] for p in pairs)
        md += [f"- **{gene}**: {len(pairs)} drugs — CPIC levels " + ", ".join(f"{k}: {v}" for k, v in sorted(lv.items())), ""][:1]
    shared = {p["drugid"] for p in pair_sets["CYP2C19"]} & {p["drugid"] for p in pair_sets["CYP2D6"]}
    md += [f"- Drugs linked to **both** genes: {len(shared)} — " + ", ".join(sorted(drugs[d]['name'] for d in shared)), ""]

    md += ["## 3. Grouping the drugs", "",
           "Two independent groupings: (a) **CPIC guideline** (the clinical grouping CPIC itself uses), "
           "(b) **WHO ATC** subgroup (from `drug.atcid`; drugs CPIC has no ATC code for are listed as 'no ATC code').", ""]
    for gene in GENES:
        by_guideline = defaultdict(list)
        by_atc = defaultdict(list)
        for p in pair_sets[gene]:
            d = drugs[p["drugid"]]
            by_guideline[guid.get(p["guidelineid"]) or "No CPIC guideline (evidence-graded association only)"].append(d["name"])
            codes = sorted({a[:4] for a in (d.get("atcid") or [])})
            by_atc[codes[0] if codes else "none"].append(d["name"])
        md += [f"### {gene} — by CPIC guideline", "", "| Guideline | # drugs | Drugs |", "|---|---|---|"]
        for k, v in sorted(by_guideline.items(), key=lambda kv: -len(kv[1])):
            md.append(f"| {k} | {len(v)} | {', '.join(sorted(v))} |")
        md += ["", f"### {gene} — by ATC subgroup", "", "| ATC | Subgroup | # drugs | Drugs |", "|---|---|---|---|"]
        for k, v in sorted(by_atc.items(), key=lambda kv: -len(kv[1])):
            md.append(f"| {k} | {ATC4.get(k, 'no ATC code in CPIC' if k == 'none' else '?')} | {len(v)} | {', '.join(sorted(v))} |")
        l1 = Counter(k[0] for k, v in by_atc.items() for _ in v if k != "none")
        md += ["", f"By ATC first level: " + ", ".join(f"{ATC1.get(k, k)} ({n})" for k, n in l1.most_common())
               + f"; no ATC code: {len(by_atc.get('none', []))}.", ""]
    OUT.write_text("\n".join(md) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
